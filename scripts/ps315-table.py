#!/usr/bin/env python3
"""Generate anonymize/ps315_table.go from PS3.15 Table E.1-1.

Reads the standard's DocBook source, as published at
https://dicom.nema.org/medical/dicom/current/source/docbook/part15/part15.xml
and writes, for every attribute of Table E.1-1, its name, its tag and its code
in the Basic Profile column and in each option column, exactly as the standard
writes them (X/Z/D and the like are not resolved). It also writes the action
the library applies for the Basic Profile column, which is those codes resolved
toward keeping the attribute and removing its content.

    python3 scripts/ps315-table.py part15.xml | gofmt > anonymize/ps315_table.go
"""
import re
import sys
import xml.etree.ElementTree as ET

DB = "{http://docbook.org/ns/docbook}"
XML_ID = "{http://www.w3.org/XML/1998/namespace}id"

# The columns after the Basic Profile one, in the order the table has them,
# paired with the Go name of each ProfileColumn.
COLUMNS = [
    "ColumnBasic",
    "ColumnRetainSafePrivate",
    "ColumnRetainUIDs",
    "ColumnRetainDeviceIdentity",
    "ColumnRetainInstitutionIdentity",
    "ColumnRetainPatientCharacteristics",
    "ColumnRetainLongitudinalFullDates",
    "ColumnRetainLongitudinalModifiedDates",
    "ColumnCleanDescriptors",
    "ColumnCleanStructuredContent",
    "ColumnCleanGraphics",
]

# How a Basic Profile code is applied. A choice of actions is resolved toward
# keeping the attribute and removing its content: an object stripped of a
# Type 1 attribute is no longer a valid object, and an invalid object is not a
# safe one.
RESOLVED = {
    "X": "ActionRemove",
    "Z": "ActionEmpty",
    "D": "ActionDummy",
    "U": "ActionUID",
    "X/D": "ActionDummy",
    "X/Z": "ActionEmpty",
    "Z/D": "ActionDummy",
    "X/Z/D": "ActionDummy",
    "X/Z/U*": "ActionUID",
}


def text(e):
    return " ".join("".join(e.itertext()).split())


def main():
    root = ET.parse(sys.argv[1]).getroot()
    subtitle = " ".join("".join(root.find(DB + "subtitle").itertext()).split())
    edition = re.search(r"PS3\.15 (\d{4}[a-z])", subtitle).group(1)
    table = [t for t in root.iter(DB + "table") if t.get(XML_ID) == "table_E.1-1"][0]
    head = [text(c) for c in table.find(DB + "thead").find(DB + "tr")]
    assert len(head) == 4 + len(COLUMNS), head
    rows = []
    for tr in table.find(DB + "tbody").iter(DB + "tr"):
        cells = [text(c) for c in tr]
        assert len(cells) == len(head), cells
        rows.append(cells)

    plain, patterns = [], []
    for cells in rows:
        name, tagtext, codes = cells[0], cells[1], cells[4:]
        m = re.fullmatch(r"\(([0-9A-F]{4}),([0-9A-F]{4})\)", tagtext)
        if m:
            plain.append((int(m.group(1), 16), int(m.group(2), 16), "", name, codes))
            continue
        m = re.fullmatch(r"\(([0-9A-F]{2})xx,(xxxx|[0-9A-F]{4})\)", tagtext)
        if m:
            group = int(m.group(1), 16) << 8
            element = 0 if m.group(2) == "xxxx" else int(m.group(2), 16)
            patterns.append((group, element, tagtext, name, codes))
            continue
        # "(gggg,eeee) where gggg is odd": private attributes, which the
        # library handles by the safe private table, not by a row.
        assert tagtext.startswith("(gggg,eeee)"), tagtext
    plain.sort()
    patterns.sort()

    out = [f"""// Code generated by scripts/ps315-table.py from DICOM PS3.15 {edition}
// Table E.1-1. DO NOT EDIT.

package anonymize

import "github.com/amrshadid/go-dicom/tag"

// ProfileTableEdition is the edition of the DICOM Standard that Table E.1-1
// was generated from.
const ProfileTableEdition = "{edition}"

// ps315BasicProfile is the action the library applies for each attribute the
// Basic Profile column names: its code resolved toward keeping the attribute
// and removing its content, which is what dcmtk and dicom-anonymizer also do.
// An attribute absent from it is left alone, because the profile is a floor
// and silently discarding data the standard did not ask about is its own kind
// of wrong.
var ps315BasicProfile = map[tag.Tag]Action{{"""]
    for group, element, _, _, codes in plain:
        out.append(f"\ttag.New(0x{group:04X}, 0x{element:04X}): {RESOLVED[codes[0]]}, // {codes[0]}")
    out.append("}")

    out.append(f"""
// ps315Rows is Table E.1-1 as the standard writes it: {len(plain)} attributes
// named by one tag, then {len(patterns)} named by a range of groups, each with
// its code in every column.
var ps315Rows = []ps315Row{{""")
    for group, element, pattern, name, codes in plain + patterns:
        cs = ", ".join('"%s"' % c for c in codes)
        name_go = '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"'
        out.append(f'\t{{tag.New(0x{group:04X}, 0x{element:04X}), "{pattern}", {name_go}, [numColumns]string{{{cs}}}}},')
    out.append("}")
    print("\n".join(out))
    print(f"{len(plain)} attributes, {len(patterns)} patterns, edition {edition}", file=sys.stderr)


main()
