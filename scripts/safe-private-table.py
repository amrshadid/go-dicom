#!/usr/bin/env python3
"""Generate anonymize/safe_private_table.go from PS3.15 Table E.3.10-1.

The Retain Safe Private Option keeps only the private attributes this table
lists as known to be safe (PS3.15 E.3.10), each named by its private creator
and its element within the creator's block. Reads the standard's HTML for
section E.3.10, as published at
https://dicom.nema.org/medical/dicom/current/output/chtml/part15/sect_E.3.10.html

    python3 scripts/safe-private-table.py sect_E.3.10.html | gofmt > anonymize/safe_private_table.go
"""
import html
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
edition = re.search(r"DICOM PS3\.15 (\d{4}[a-z])", text)
rows = []
for row in re.findall(r"<tr[^>]*>(.*?)</tr>", text, re.S):
    cells = [" ".join(html.unescape(re.sub(r"<[^>]+>", "", c)).split())
             for c in re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)]
    if len(cells) < 4:
        continue
    m = re.fullmatch(r"\(([0-9A-Fa-f]{4}),xx([0-9A-Fa-f]{2})\)", cells[0].replace(" ", ""))
    if not m:
        continue
    rows.append((int(m.group(1), 16), cells[1], int(m.group(2), 16), cells[2]))

rows = sorted(set(rows), key=lambda r: (r[1], r[0], r[2]))
out = [f"""// Code generated by scripts/safe-private-table.py from DICOM PS3.15
// {edition.group(1) if edition else ''} Table E.3.10-1. DO NOT EDIT.

package anonymize

// safePrivateAttributes are the private attributes the Retain Safe Private
// Option keeps (PS3.15 E.3.10): {len(rows)} entries, each a private creator, its
// group and the element within the creator's block.
var safePrivateAttributes = map[safePrivateKey]bool{{"""]
for group, creator, element, vr in rows:
    creator_go = '"' + creator.replace("\\", "\\\\").replace('"', '\\"') + '"'
    out.append(f"\t{{0x{group:04X}, {creator_go}, 0x{element:02X}}}: true, // {vr}")
out.append("}")
print("\n".join(out))
print(f"{len(rows)} safe private attributes", file=sys.stderr)
