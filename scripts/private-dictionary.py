#!/usr/bin/env python3
"""Generate tag/gen_private_dictionary.go from pydicom's private dictionary.

pydicom's table is generated from GDCM's private dictionary, which was compiled
from vendor conformance statements; see THIRD_PARTY_NOTICES for both licenses.
It replaces a table that was itself generated, with VRs given in rotation, and
that this library had to stop trusting (#186, #188).

    python3 scripts/private-dictionary.py <pydicom src dir> > tag/gen_private_dictionary.go

Keys are normalized to block 0x10, as tag.GetPrivateTagInfo looks them up:
GDCM's "0019xx08" is stored as 0x00191008. An entry giving the element in
full is used where it falls in block 0x10 and no "xx" entry covers it; one
below 0x1000, such as Canon's (0029,0001), is not in a private block at all,
so the block-normalized lookup could never reach it, and it is left out, as
are repeating-group entries ("60xx...").
"""
import re
import sys

sys.path.insert(0, sys.argv[1])
from pydicom._private_dict import private_dictionaries  # noqa: E402

HEADER = """// Code generated by scripts/private-dictionary.py from pydicom's private
// dictionary, which is generated from GDCM's. DO NOT EDIT.
//
// GDCM (Grassroots DICOM):
// Copyright (c) 2006-2016 Mathieu Malaterre
// Copyright (c) 1993-2005 CREATIS
// All rights reserved. Redistributed under the BSD 3-Clause license given in
// THIRD_PARTY_NOTICES, which also carries pydicom's MIT license.

package tag
"""


def keyword(name):
    words = re.findall(r"[A-Za-z0-9]+", name)
    out = "".join(w[:1].upper() + w[1:] for w in words)
    if out and out[0].isdigit():
        out = "X" + out
    return out


def vr(value):
    value = value.strip()
    if value == "OB_OW":
        return "OB or OW"
    return value


entries = {}
skipped = 0
for creator in sorted(private_dictionaries):
    table = {}
    literal = {}
    for key, (v, vm, name, retired) in private_dictionaries[creator].items():
        m = re.fullmatch(r"([0-9A-Fa-f]{4})xx([0-9A-Fa-f]{2})", key)
        if m:
            target = table
        else:
            m = re.fullmatch(r"([0-9A-Fa-f]{4})([0-9A-Fa-f]{2})([0-9A-Fa-f]{2})", key)
            if not m or int(m.group(2), 16) < 0x10:
                skipped += 1
                continue
            target = literal
        group, element = int(m.group(1), 16), int(m.groups()[-1], 16)
        if group % 2 == 0:
            skipped += 1
            continue
        target[(group << 16) | 0x1000 | element] = (vr(v), vm, name, retired == "R")
    for t, info in literal.items():
        table.setdefault(t, info)
    if table:
        entries[creator] = table


def go_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


total = sum(len(t) for t in entries.values())
out = [HEADER]
out.append("// privateDictionary contains private DICOM tags organized by private creator,")
out.append("// each tag normalized to block 0x10.")
out.append(f"// Total: {len(entries)} creators, {total} tags.")
out.append("var privateDictionary = map[string]map[uint32]TagInfo{")
for creator in sorted(entries):
    out.append(f"\t{go_string(creator)}: {{")
    for t in sorted(entries[creator]):
        v, vm, name, retired = entries[creator][t]
        out.append(f"\t\t0x{t:08X}: {{Tag: 0x{t:08X}, VR: {go_string(v)}, VM: {go_string(vm)}, "
                   f"Name: {go_string(name)}, Retired: {'true' if retired else 'false'}, "
                   f"Keyword: {go_string(keyword(name))}}},")
    out.append("\t},")
out.append("}")
print("\n".join(out))
print(f"{len(entries)} creators, {total} tags, {skipped} entries skipped", file=sys.stderr)
