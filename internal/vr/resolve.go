package vr

import (
	"encoding/binary"
	"strings"

	"github.com/amrshadid/go-dicom/tag"
)

// Scope is a data set as far as settling a VR reads it: the bytes of an
// element in it, by tag.
//
// dataset.Dataset and the codec-free DICOM JSON writer each give their own, so
// the rules below are written once and the two cannot drift.
type Scope interface {
	// Bytes returns the bytes of the element at t, and false when the data set
	// has no such element or it holds no bytes (a sequence, a value still in a
	// file).
	Bytes(t tag.Tag) ([]byte, bool)
}

var (
	bitsAllocatedTag       = tag.New(0x0028, 0x0100)
	pixelRepresentationTag = tag.New(0x0028, 0x0103)
	lutDescriptorTag       = tag.New(0x0028, 0x3002)
	lutDataTag             = tag.New(0x0028, 0x3006)
	pixelDataTag           = tag.New(0x7FE0, 0x0010)
)

// IsBinary reports whether a VR is carried as binary rather than as numbers or
// text: OB, OD, OF, OL, OV, OW and UN.
func IsBinary(vr string) bool {
	switch vr {
	case "OB", "OD", "OF", "OL", "OV", "OW", "UN":
		return true
	}
	return false
}

// fixedSize is the width of one value of the VRs that have one.
var fixedSize = map[string]int{
	"AS": 4, "AT": 4, "DA": 8, "FD": 8, "FL": 4, "SL": 4, "SS": 2, "US": 2,
	"SV": 8, "UV": 8, "UL": 4,
}

// Resolve settles the one VR an element is written with. It is the rule
// dataset.ResolveVR documents, given the element as its parts: the VR it
// carries ("" for none), whether it holds a sequence, its bytes (rawOK false
// when it has none), the data set it is in and the ones that data set is an
// item of, nearest first. outers must hold no nil.
func Resolve(t tag.Tag, vr string, sequence bool, raw []byte, rawOK bool, scope Scope, outers []Scope) string {
	if sequence {
		return "SQ"
	}
	if vr == "" {
		if private := PrivateVR(t, raw, rawOK, scope); private != "" {
			return private
		}
		vr = t.GetVR()
		if vr == "SQ" {
			// The value is bytes, not items. Claiming SQ would describe a
			// structure nobody parsed.
			return "UN"
		}
	}
	if OffersChoice(vr) {
		vr = resolveAmbiguous(t, vr, scope, outers)
	}
	if len(vr) != 2 {
		return "UN"
	}
	return vr
}

// PrivateVR resolves a private tag through the private dictionary, or returns
// "" when nothing can say. raw and rawOK are the element's own bytes.
//
// Private tags cannot be looked up by their stored tag, because the block they
// sit in is assigned per file. PS3.5 7.8.1 gives a vendor a group and lets it
// claim any block from 0x10 to 0xFF within it; the block is named by a private
// creator at (gggg,00xx), and the vendor's attributes then live at (gggg,xxee).
// The same attribute is (0019,1002) in one file and (0019,4302) in the next.
//
// So the creator is read to learn the vendor, and the tag is normalized to the
// block the dictionary stores it under before the lookup. Without that step a
// dictionary of 6883 private attributes answers nothing except for files that
// happen to have chosen block 0x10.
//
// The dictionary is GDCM's, generated by scripts/private-dictionary.py. The
// table it replaced was itself generated, with VRs given in rotation, and
// trusting that one relabeled real data, so for a while nothing was trusted
// and every private attribute was UN (#186). An entry with an unambiguous VR
// is used again; anything else stays UN (#188).
func PrivateVR(t tag.Tag, raw []byte, rawOK bool, scope Scope) string {
	if t.Group()%2 == 0 {
		return ""
	}

	element := t.Element()

	// A private creator is LO by definition — its value is the vendor's own
	// name, so no dictionary is needed or possible.
	if element >= 0x0010 && element <= 0x00FF {
		return "LO"
	}

	block := element >> 8
	if block < 0x10 {
		return "" // not a private data element of any block
	}
	creator, ok := scope.Bytes(tag.New(t.Group(), block))
	if !ok {
		return "" // the block was never claimed, so nothing can say what this is
	}
	vendor := strings.TrimRight(string(creator), " \x00")
	if vendor == "" {
		return ""
	}

	canonical := tag.New(t.Group(), 0x1000|(element&0x00FF))
	if info := canonical.GetPrivateTagInfo(vendor); info != nil {
		known := info.VR
		if known != "" && known != "UN" && known != "SQ" && !IsBinary(known) &&
			!OffersChoice(known) && fits(known, raw, rawOK) {
			return known
		}
	}
	return ""
}

// fits reports whether the value is a whole number of values of a fixed-size
// VR, or the VR is not fixed-size. A dictionary can be wrong for one device's
// software version, and labeling 2 bytes FL is the file pydicom refuses that
// #186 produced; such a value stays UN.
func fits(vr string, raw []byte, rawOK bool) bool {
	width := fixedSize[vr]
	if width <= 0 {
		return true
	}
	return !rawOK || len(raw)%width == 0
}

// resolveAmbiguous applies the rules dataset.ResolveVR describes to a
// dictionary VR that offers a choice.
func resolveAmbiguous(t tag.Tag, vr string, scope Scope, outers []Scope) string {
	switch {
	case t == pixelDataTag:
		if bits, ok := uint16Value(scope, bitsAllocatedTag); ok && bits <= 8 {
			return "OB"
		}
		return "OW"

	case t == lutDataTag:
		if entries, ok := uint16Value(scope, lutDescriptorTag); ok && entries == 1 {
			return "US"
		}
		return "OW"

	case vr == "US or SS":
		if unsignedPixelValues(scope, outers) {
			return "US"
		}
		return "SS"

	case strings.Contains(vr, "OW"):
		return "OW"

	case vr == "OB or OD":
		return "OB"
	}
	return vr
}

// unsignedPixelValues reports what Pixel Representation says, taken from the
// nearest data set that has it. Absent everywhere, it is 0 — unsigned — which is
// the standard's default and the common case.
func unsignedPixelValues(scope Scope, outers []Scope) bool {
	if v, ok := uint16Value(scope, pixelRepresentationTag); ok {
		return v == 0
	}
	for _, outer := range outers {
		if v, ok := uint16Value(outer, pixelRepresentationTag); ok {
			return v == 0
		}
	}
	return true
}

// uint16Value reads the first value of a two-byte unsigned element.
func uint16Value(scope Scope, t tag.Tag) (uint16, bool) {
	raw, ok := scope.Bytes(t)
	if !ok || len(raw) < 2 {
		return 0, false
	}
	return binary.LittleEndian.Uint16(raw), true
}
