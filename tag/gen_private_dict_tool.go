func makeKeyword(name string) string {
	words := strings.Fields(name)
	keyword := ""
	for _, w := range words {
		if len(w) > 0 {
			keyword += strings.ToUpper(w[:1]) + strings.ToLower(w[1:])
		}
	}
	// Remove non-alphanumeric
	result := ""
	for _, c := range keyword {
		if (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') {
			result += string(c)
		}
	}
	return result
}

