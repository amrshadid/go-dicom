//go:build ignore

// This program generates gen_private_dictionary.go containing the private DICOM tag dictionary.
// Run with: go run gen_private_dict_tool.go
package main

import (
	"fmt"
	"os"
	"strings"
)

type vendorDef struct {
	name string
	tags []tagDef
}

type tagDef struct {
	group   uint16
	element uint16
	vr      string
	vm      string
	name    string
	keyword string
}

func main() {
	vendors := buildVendors()

	f, err := os.Create("gen_private_dictionary.go")
	if err != nil {
		panic(err)
	}
	defer f.Close()

	totalTags := 0
	for _, v := range vendors {
		totalTags += len(v.tags)
	}

	fmt.Fprintln(f, "package tag")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "// privateDictionary contains private DICOM tags organized by vendor.")
	fmt.Fprintln(f, "// Generated by gen_private_dict_tool.go - DO NOT EDIT.")
	fmt.Fprintf(f, "// Total: %d vendors, %d tags.\n", len(vendors), totalTags)
	fmt.Fprintln(f, "var privateDictionary = map[string]map[uint32]TagInfo{")

	for _, v := range vendors {
		fmt.Fprintf(f, "\t%q: {\n", v.name)
		for _, t := range v.tags {
			tagVal := (uint32(t.group) << 16) | uint32(t.element)
			fmt.Fprintf(f, "\t\t0x%08X: {Tag: 0x%08X, VR: %q, VM: %q, Name: %q, Keyword: %q},\n",
				tagVal, tagVal, t.vr, t.vm, t.name, t.keyword)
		}
		fmt.Fprintln(f, "\t},")
	}

	fmt.Fprintln(f, "}")

	fmt.Printf("Generated %d vendors, %d tags\n", len(vendors), totalTags)
}

