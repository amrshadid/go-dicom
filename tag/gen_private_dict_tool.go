func generateVendorTags(vendor string, baseGroup uint16, count int) []tagDef {
	// Ensure odd group (private tags must have odd group numbers)
	if baseGroup%2 == 0 {
		baseGroup++
	}

	vrs := []string{"LO", "SH", "DS", "IS", "US", "UL", "SS", "SL", "FD", "FL", "CS", "DA", "TM", "UI", "OB", "OW", "ST", "LT", "PN", "AT"}
	names := tagNamesForVendor(vendor)

	tags := make([]tagDef, 0, count)
	for i := 0; i < count; i++ {
		elem := uint16(0x1001 + i)
		vr := vrs[i%len(vrs)]
		name := names[i%len(names)]
		keyword := makeKeyword(name)
		tags = append(tags, tagDef{
			group:   baseGroup,
			element: elem,
			vr:      vr,
			vm:      "1",
			name:    name,
			keyword: keyword,
		})
	}
	return tags
}

